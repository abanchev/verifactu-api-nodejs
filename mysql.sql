CREATE TABLE IF NOT EXISTS `companies` (
  `id` int(11) unsigned NOT NULL AUTO_INCREMENT,
  `code` varchar(25) NOT NULL,
  `name` varchar(50) NOT NULL,
  `vat_id` varchar(25) NOT NULL,
  `address` varchar(75) NOT NULL,
  `postal_code` varchar(10) NOT NULL,
  `city` varchar(25) NOT NULL,
  `state` varchar(25) NOT NULL,
  `country` char(2) NOT NULL DEFAULT 'ES',
  `email` varchar(50) DEFAULT NULL,
  `phone` varchar(50) DEFAULT NULL,
  `contact` varchar(50) DEFAULT NULL,
  `formula` varchar(25) NOT NULL DEFAULT '%n%',
  `formula_r` varchar(25) NOT NULL DEFAULT 'R-%n%',
  `first_num` int(11) unsigned NOT NULL DEFAULT 1,
  `created` date NOT NULL,
  `next_send` datetime DEFAULT NULL,
  `test` tinyint(1) NOT NULL DEFAULT 1,
  `cert_key` text DEFAULT NULL,
  `cert_content` text DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `code` (`code`),
  UNIQUE KEY `vat_id` (`vat_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `invoices` (
  `id` int(11) unsigned NOT NULL AUTO_INCREMENT,
  `company_id` int(11) unsigned NOT NULL,
  `dt` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `num` int(11) unsigned NOT NULL,
  `name` varchar(50) NOT NULL,
  `vat_id` varchar(25) DEFAULT NULL,
  `address` varchar(75) DEFAULT NULL,
  `postal_code` varchar(10) DEFAULT NULL,
  `city` varchar(25) DEFAULT NULL,
  `state` varchar(25) DEFAULT NULL,
  `country` char(2) DEFAULT NULL,
  `tvat` double NOT NULL DEFAULT 0,
  `bi` double NOT NULL DEFAULT 0,
  `total` double NOT NULL DEFAULT 0,
  `email` varchar(50) DEFAULT NULL,
  `ref` varchar(25) DEFAULT NULL,
  `comments` text DEFAULT NULL,
  `fingerprint` varchar(64) DEFAULT NULL,
  `verifactu_type` char(2) DEFAULT NULL,
  `verifactu_stype` char(1) DEFAULT NULL,
  `verifactu_dt` timestamp NULL DEFAULT NULL,
  `verifactu_csv` text DEFAULT NULL,
  `verifactu_err` int(11) unsigned DEFAULT NULL,
  `invoice_ref_id` int(11) unsigned DEFAULT NULL,
  `voided` tinyint(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_company_id` (`company_id`),
  KEY `idx_dt` (`dt`),
  KEY `idx_num` (`num`),
  KEY `idx_fingerprint` (`fingerprint`),
  KEY `idx_verifactu_type` (`verifactu_type`),
  KEY `idx_verifactu_dt` (`verifactu_dt`),
  CONSTRAINT `fk_invoices_company` FOREIGN KEY (`company_id`) REFERENCES `companies` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_invoices_ref` FOREIGN KEY (`invoice_ref_id`) REFERENCES `invoices` (`id`) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `invoice_lines` (
  `invoice_id` int(11) unsigned NOT NULL,
  `num` int(11) unsigned NOT NULL DEFAULT 0,
  `descr` varchar(100) DEFAULT NULL,
  `units` int(11) DEFAULT NULL,
  `price` double DEFAULT NULL,
  `vat` int(11) unsigned DEFAULT NULL,
  `tvat` double DEFAULT NULL,
  `bi` double DEFAULT NULL,
  `total` double DEFAULT NULL,
  PRIMARY KEY (`invoice_id`, `num`),
  KEY `idx_num` (`num`),
  CONSTRAINT `fk_lines_invoice` FOREIGN KEY (`invoice_id`) REFERENCES `invoices` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
